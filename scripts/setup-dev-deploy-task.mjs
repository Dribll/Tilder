/**
 * setup-dev-deploy-task.mjs
 *
 * ONE-TIME setup: Creates a Windows Scheduled Task "TilderDevDeploy" that
 * runs as SYSTEM (no UAC needed to trigger it) to hot-swap the freshly-built
 * TilderMonitorService.exe into Program Files and restart the service.
 *
 * Run ONCE as Administrator:
 *   node scripts/setup-dev-deploy-task.mjs
 *
 * After that, `npm run desktop:dev` and `npm run build:monitor` automatically
 * trigger this task whenever the C# source changes — zero manual steps.
 */

import { execSync } from 'node:child_process';
import fs   from 'node:fs';
import os   from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename  = fileURLToPath(import.meta.url);
const __dirname   = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');

const srcExe = path.join(projectRoot, 'src-tauri', 'windows', 'monitor_bin', 'TilderMonitorService.exe');
const dstExe = 'C:\\Program Files\\Tilder\\monitor_bin\\TilderMonitorService.exe';

// Permanent helper script (lives in the project, survives temp-folder cleanups)
const helperScript = path.join(projectRoot, 'scripts', 'deploy-service-helper.ps1');

// Write the deploy helper (what the task actually runs)
fs.writeFileSync(helperScript, `# Auto-generated by setup-dev-deploy-task.mjs — do not edit manually
# Copies the freshly-built TilderMonitorService.exe to Program Files and restarts the service.
sc.exe stop TilderMonitorService
Start-Sleep -Seconds 2
Copy-Item "${srcExe}" "${dstExe}" -Force
sc.exe start TilderMonitorService
`, 'utf8');

// Register script — creates the scheduled task
const registerPs1 = path.join(os.tmpdir(), 'tilder_register_task.ps1');
fs.writeFileSync(registerPs1, `
$action    = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument '-WindowStyle Hidden -ExecutionPolicy Bypass -File "${helperScript}"'
$settings  = New-ScheduledTaskSettingsSet -ExecutionTimeLimit (New-TimeSpan -Minutes 3) -MultipleInstances IgnoreNew
$principal = New-ScheduledTaskPrincipal -UserId 'S-1-5-18' -RunLevel Highest
Register-ScheduledTask -Force -TaskName 'TilderDevDeploy' -Action $action -Settings $settings -Principal $principal | Out-Null
Write-Host 'TASK_CREATED'
`.trim(), 'utf8');

try {
  const result = execSync(`powershell -ExecutionPolicy Bypass -File "${registerPs1}"`, { encoding: 'utf8' });

  if (result.includes('TASK_CREATED')) {
    console.log('\n✅  Scheduled task "TilderDevDeploy" created successfully.');
    console.log('    Src  : ' + srcExe);
    console.log('    Dest : ' + dstExe);
    console.log('\n    `npm run desktop:dev` and `npm run build:monitor` will now');
    console.log('    auto-deploy the service on every source change. No UAC ever.\n');
  } else {
    console.error('\nUnexpected output:', result);
    process.exit(1);
  }
} catch (e) {
  const msg = (e.stderr || e.stdout || String(e)).toString();
  if (msg.includes('Access is denied') || msg.includes('privilege') || msg.includes('elevation')) {
    console.error('\n❌  Access denied. Run as Administrator:\n');
    console.error('    Open a terminal as Admin, then:');
    console.error('    node scripts/setup-dev-deploy-task.mjs\n');
  } else {
    console.error('\n❌  Failed:', msg);
  }
  process.exit(1);
} finally {
  try { fs.unlinkSync(registerPs1); } catch {}
}
